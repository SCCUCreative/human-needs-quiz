#!/usr/bin/env python3
"""Builds data/apps-script/ArchetypeData.gs: the small slice of archetype copy the collector needs
(name, hero image, one-line summary, three "at a glance" lines), keyed by need pair.

Usage (repo root):  python3 tools/build_email_data.py [path/to/archetypes-data.js]
Defaults to tools/archetypes-data.js. Needs node. Re-run whenever the archetype copy changes.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'tools', 'archetypes-data.js')
OUT = os.path.join(ROOT, 'data', 'apps-script', 'ArchetypeData.gs')

js = ("const fs=require('fs');const D=new Function(fs.readFileSync(process.argv[1],'utf8')+';return ARCHETYPE_DATA;')();"
      "const o={};for(const [k,a] of Object.entries(D)){o[k]={name:a.name,hero:a.hero||'',"
      "together:((a.innerWorld&&a.innerWorld.together)||'').replace(/\\n/g,' '),glance:a.glance||[]};}"
      "console.log(JSON.stringify(o));")
data = json.loads(subprocess.check_output(['node', '-e', js, SRC]))
assert len(data) == 15, len(data)
body = json.dumps(data, indent=1, ensure_ascii=False)
open(OUT, 'w', encoding='utf-8').write(
    '// AUTO-GENERATED by tools/build_email_data.py from archetypes-data.js. Do not edit by hand.\n'
    '// Keyed by need pair in canonical order (certainty < variety < significance < connection < growth < contribution).\n'
    'var ARCHETYPES = ' + body + ';\n')
print('wrote', OUT, len(data), 'archetypes')
